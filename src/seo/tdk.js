function clean(value) {
  return String(value ?? "").replace(/\s+/g, " ").trim();
}

function detailName(collection, name) {
  const value = clean(name);
  if (collection === "guides") return value;
  if (collection === "bosses") return value.replace(/\s+(?:(?:Mini-)?Boss(?:\s+Guide)?|Final Boss|Guide)$/i, "").trim();
  return value.replace(/\s+Guide$/i, "").trim();
}

function fitTitle(name, middle, suffix) {
  const ending = ` - ${suffix}`;
  let head = `${clean(name)}${middle}`;
  let title = `${head}${ending}`;
  if (title.length < 40 && !/\bguide$/i.test(head)) title = `${head} Guide${ending}`;
  if (title.length < 40) title = `${head} Complete Guide${ending}`;
  if (title.length <= 60) return title;
  const maxName = Math.max(8, 60 - middle.length - ending.length);
  let shortened = clean(name).slice(0, maxName).replace(/\s+\S*$/, "").trim();
  if (!shortened) shortened = clean(name).slice(0, maxName).trim();
  head = `${shortened}${middle}`;
  return `${head}${ending}`;
}

function fitDescription(value) {
  let description = clean(value);
  if (description.length > 160) {
    description = description.slice(0, 159).replace(/[,;:\s]+\S*$/, "").replace(/[,.!?;:]+$/, "");
    return `${description}.`;
  }
  return description;
}

export function getDetailTdk(collection, entry, path) {
  if (collection === "guides" && entry.slug === "beginner-guide") {
    return {
      title: "How to Fish Beginner Guide: Tips & Early Progression",
      description: "Start How to Fish with beginner fishing tips, Lighthouse quests, selling, the Crab Fishing Rod, boat key, Radar and early weapon priorities.",
      keywords: ["How to Fish beginner guide", "How to Fish tips", "How to Fish early progression", "How to Fish Lighthouse guide", "How to Fish fishing controls"],
      path,
      lastModified: entry.updated ?? "2026-08-24",
    };
  }
  if (collection === "guides" && entry.slug === "full-walkthrough") {
    return {
      title: "How to Fish Walkthrough: All Islands, Bosses & Quests",
      description: "Complete the How to Fish walkthrough from Lighthouse to Volcano with all island unlocks, boss triggers, bait requirements, trophies and NPC hand-ins.",
      keywords: ["How to Fish walkthrough", "How to Fish all islands", "How to Fish boss guide", "How to Fish quest walkthrough", "How to Fish island unlocks"],
      path,
      lastModified: entry.updated ?? "2026-08-24",
    };
  }
  if (collection === "bosses") {
    const bossName = detailName(collection, entry.name);
    const fullTitle = `${bossName} Boss Strategy - How to Fish Steam Guide`;
    return {
      title: fullTitle.length <= 60 ? fullTitle : `${bossName} Boss Strategy - How to Fish Guide`,
      description: clean(entry.seoDescription ?? entry.description),
      keywords: [bossName, `${bossName} How to Fish`, `${bossName} boss strategy`, `${bossName} boss guide`, "How to Fish bosses", ...(entry.tags ?? []).slice(0, 2)],
      path,
      lastModified: entry.updated ?? "2026-08-24",
    };
  }
  const label = detailLabels[collection] ?? detailLabels.guides;
  const context = clean(entry.description).replace(/[.!?]+$/, "");
  const description = fitDescription(`${context}. This ${label.noun.toLowerCase()} page covers ${label.topics} in How to Fish.`);
  return {
    title: fitTitle(detailName(collection, entry.name), label.middle, label.suffix),
    description,
    keywords: [entry.name, `${entry.name} How to Fish`, `How to Fish ${label.noun.toLowerCase()}`, ...(entry.tags ?? []).slice(0, 4)],
    path,
    lastModified: entry.updated ?? "2026-08-24",
  };
}

export function getFishTdk(entry, content, path) {
  const method = entry.catchMethods?.[0];
  const isGroundPickup = method?.methodType === "Ground pickup";
  const isAmbient = entry.creatureStatus === "Ambient";
  const isUnconfirmed = method?.methodType === "Unconfirmed";
  const poolDetail = method?.poolShare !== undefined
    ? ` Extracted pool weight: ${method.rawWeight} (${method.poolShare.toFixed(method.poolShare % 1 ? 2 : 0)}%).`
    : "";
  const description = isGroundPickup
    ? `Find ${entry.name} on ${entry.islandName} as a direct ground pickup; no rod or bait is required. It is a ${entry.progression ?? "collection"} ${entry.creatureGroup ?? "special"} record outside fishing pools.`
    : isAmbient
      ? `${entry.name} is an ambient ${entry.sourceClass ?? "special"} creature referenced by the game scenes. Its exact spawn route, sell value and Collector slot need live-build confirmation.`
    : isUnconfirmed
        ? `${entry.name} is associated with ${entry.islandName}, but the unpacked data does not confirm a repeatable rod-and-bait pool. Verify the live route before spending a lure.`
        : `Find ${entry.name} on ${entry.islandName} with the ${entry.rod} and ${entry.lure}.${poolDetail} Check its sell value and collection status.`;
  return {
    title: fitTitle(entry.name, " Creature Location & Bait", "How to Fish Steam Guide"),
    description: fitDescription(description),
    keywords: [entry.name, `${entry.name} How to Fish`, `${entry.name} bait`, `${entry.name} location`, "How to Fish creatures"],
    path,
    lastModified: content.updated ?? "2026-08-24",
  };
}

