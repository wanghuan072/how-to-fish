function clean(value) {
  return String(value ?? "").replace(/\s+/g, " ").trim();
}

function detailName(collection, name) {
  const value = clean(name);
  if (collection === "guides") return value;
  if (collection === "bosses") return value.replace(/\s+(?:Final\s+)?Boss(?:\s+Guide)?$/i, "").trim();
  return value.replace(/\s+Guide$/i, "").trim();
}

function fitTitle(name, middle, suffix) {
  const ending = ` - ${suffix}`;
  let head = `${clean(name)}${middle}`;
  let title = `${head}${ending}`;
  if (title.length < 40 && !/\bguide$/i.test(head)) title = `${head} Guide${ending}`;
  if (title.length < 40) title = `${head} Complete Guide${ending}`;
  if (title.length <= 60) return title;
  const maxName = Math.max(8, 60 - middle.length - ending.length);
  let shortened = clean(name).slice(0, maxName).replace(/\s+\S*$/, "").trim();
  if (!shortened) shortened = clean(name).slice(0, maxName).trim();
  head = `${shortened}${middle}`;
  return `${head}${ending}`;
}

function fitDescription(value) {
  let description = clean(value);
  if (description.length > 160) {
    description = description.slice(0, 159).replace(/[,;:\s]+\S*$/, "").replace(/[,.!?;:]+$/, "");
    return `${description}.`;
  }
  const filler = " Open the connected pages to plan the next step without losing a quest item.";
  while (description.length < 140) description += filler;
  if (description.length > 160) {
    description = description.slice(0, 159).replace(/[,;:\s]+\S*$/, "").replace(/[,.!?;:]+$/, "");
    description += ".";
  }
  return description;
}

export function getDetailTdk(collection, entry, path) {
  const label = detailLabels[collection] ?? detailLabels.guides;
  const context = clean(entry.description).replace(/[.!?]+$/, "");
  const description = fitDescription(`${context}. This ${label.noun.toLowerCase()} page covers ${label.topics} in How to Fish.`);
  return {
    title: fitTitle(detailName(collection, entry.name), label.middle, label.suffix),
    description,
    keywords: [entry.name, `${entry.name} How to Fish`, `How to Fish ${label.noun.toLowerCase()}`, ...(entry.tags ?? []).slice(0, 4)],
    path,
    lastModified: entry.updated ?? "2026-08-24",
  };
}

